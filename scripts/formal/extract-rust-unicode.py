#!/usr/bin/env python3
"""Copy the pinned Rust Unicode skip tables into inspectable Agda source data.

This extractor is not a proof oracle. Agda checks table invariants separately;
the retained source digest and exact arrays make transcription reviewable.
"""
import argparse
import hashlib
from pathlib import Path
import re


def extract(source, name):
    module = re.search(rf"pub mod {name} \{{(.*?)\n\}}", source, re.S).group(1)
    headers = re.search(r"static SHORT_OFFSET_RUNS:.*?; (\d+)\] = \[(.*?)\];", module, re.S)
    pairs = [tuple(map(int, pair)) for pair in re.findall(
        r"ShortOffsetRunHeader::new\((\d+), (\d+)\)", headers.group(2))]
    offsets = re.search(r"static OFFSETS: \[u8; (\d+)\] = \[(.*?)\];", module, re.S)
    values = list(map(int, re.findall(r"\d+", offsets.group(2))))
    assert len(pairs) == int(headers.group(1))
    assert len(values) == int(offsets.group(1))
    return pairs, values


def agda_list(values, per_line):
    lines = []
    for begin in range(0, len(values), per_line):
        lines.append("  " + " ∷ ".join(values[begin:begin + per_line]) + " ∷")
    return "\n".join(lines) + "\n  []\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("destination", type=Path)
    args = parser.parse_args()
    raw = args.source.read_bytes()
    source = raw.decode()
    assert "UNICODE_VERSION: (u8, u8, u8) = (17, 0, 0)" in source
    result = ["{-# OPTIONS --safe #-}\n",
              "-- Complete source tables, not selected examples. Generated by\n",
              "-- scripts/formal/extract-rust-unicode.py from Rust 1.99.0.\n",
              f"-- unicode_data.rs SHA-256: {hashlib.sha256(raw).hexdigest()}\n",
              "module Mimir.RustUnicodeData where\n\n",
              "open import Data.List using (List; []; _∷_)\n",
              "open import Data.Nat using (ℕ)\n",
              "open import Data.Product using (_×_; _,_)\n\n"]
    for rust_name, agda_name in [("alphabetic", "alphabetic"), ("n", "numeric")]:
        pairs, values = extract(source, rust_name)
        result += [f"{agda_name}Headers : List (ℕ × ℕ)\n",
                   f"{agda_name}Headers =\n",
                   agda_list([f"({a} , {b})" for a, b in pairs], 4), "\n",
                   f"{agda_name}Offsets : List ℕ\n",
                   f"{agda_name}Offsets =\n",
                   agda_list(list(map(str, values)), 20), "\n"]
        print(f"{rust_name}: {len(pairs)} headers, {len(values)} offsets")
    args.destination.write_text("".join(result))
    print(f"source_sha256={hashlib.sha256(raw).hexdigest()}")
    print(f"destination={args.destination}")


if __name__ == "__main__":
    main()
